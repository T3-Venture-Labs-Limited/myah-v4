import { TWENTY_STANDARD_APPLICATION_UNIVERSAL_IDENTIFIER } from 'twenty-shared/application';

export const RETIRED_BRAND_BRAIN_APPLICATION_UNIVERSAL_IDENTIFIER =
  '2f7d88d6-c6c9-4ed2-87e2-c1f9f13f3991';

export const RETIRED_SHOPIFY_APPLICATION_UNIVERSAL_IDENTIFIER =
  'a51fd2e5-b101-48f2-b1f8-cbc0a591e8ef';

export const RETAINED_INSTAGRAM_APPLICATION_UNIVERSAL_IDENTIFIER =
  '4738ebcd-6662-4ecc-a190-374fa0525951';

const RETIRED_APPLICATION_UNIVERSAL_IDENTIFIERS = new Set([
  RETIRED_BRAND_BRAIN_APPLICATION_UNIVERSAL_IDENTIFIER,
  RETIRED_SHOPIFY_APPLICATION_UNIVERSAL_IDENTIFIER,
]);

const SUPPORTED_APPLICATION_UNIVERSAL_IDENTIFIERS = new Set([
  TWENTY_STANDARD_APPLICATION_UNIVERSAL_IDENTIFIER,
  RETAINED_INSTAGRAM_APPLICATION_UNIVERSAL_IDENTIFIER,
]);

export const isRetiredApplicationUniversalIdentifier = (
  universalIdentifier: string,
): boolean =>
  RETIRED_APPLICATION_UNIVERSAL_IDENTIFIERS.has(universalIdentifier);

export const isSupportedApplicationUniversalIdentifier = (
  universalIdentifier: string,
): boolean =>
  SUPPORTED_APPLICATION_UNIVERSAL_IDENTIFIERS.has(universalIdentifier);
